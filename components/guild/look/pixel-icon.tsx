export function PixelIcon({
  icon,
  size = 36,
  color = "#d4b46a",
  accent = "#ffffff",
  className,
}: {
  icon: JobIconKey;
  size?: number;
  color?: string;
  accent?: string;
  className?: string;
}) {
  const rows = MAPS[icon] ?? MAPS.owner;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 12 12"
      shapeRendering="crispEdges"
      aria-hidden
      className={className}
    >
      {rows.flatMap((row, y) =>
        [...row].map((c, x) =>
          c === "1" || c === "2" ? (
            <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={c === "1" ? color : accent} />
          ) : null,
        ),
      )}
    </svg>
  );
}
