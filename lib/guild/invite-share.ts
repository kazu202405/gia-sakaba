/** 入会画面のURL。招待コードはURLに入れるので必ずエンコードする。 */
export function inviteUrl(origin: string, code: string): string {
  return `${origin.replace(/\/+$/, "")}/guild/join?invite=${encodeURIComponent(code)}`;
}

